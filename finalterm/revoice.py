#!/usr/bin/env python3
"""Rewrite the Persian pronunciations (Units 1-8) and difficulty labels
(Units 1-4) inside data-en2.js.

Pronunciations are generated by phonetics.py (espeak-ng IPA -> Persian
phonetic spelling). Difficulty for Units 1-4 is judged from word frequency
plus word shape instead of the old length heuristic; the frequency list
(50k English words, FrequencyWords) is only needed while running:

    curl -sSLo /tmp/en50k.txt \
      https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/en/en_50k.txt
    python3 finalterm/revoice.py [--dry]

The Units 5-8 sources (finalterm/src/u*.psv) are kept in sync so that
build.py reproduces the same output.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE.parent / "data-en2.js"
FREQ = Path("/tmp/en50k.txt")

sys.path.insert(0, str(HERE))
from phonetics import pron  # noqa: E402

ENTRY = re.compile(
    r'(?P<indent>\s*)\{ en: "(?P<en>(?:[^"\\]|\\.)*)", '
    r'pron: "(?P<pron>(?:[^"\\]|\\.)*)", '
    r'fa: "(?P<fa>(?:[^"\\]|\\.)*)", '
    r'difficulty: "(?P<difficulty>easy|hard)" \},'
)
UNIT = re.compile(r"^    (u\d): \{$", re.M)

ACADEMIC = re.compile(
    r"(tion|sion|ment|ness|ity|ance|ence|ous|ial|ify|iz|ate|ism|ist|ive|able|ible)$"
)


def load_freq():
    if not FREQ.exists():
        sys.exit(f"missing {FREQ}; see the download command in this file")
    rank = {}
    for i, line in enumerate(FREQ.read_text(encoding="utf-8").splitlines()):
        parts = line.split()
        if parts:
            rank.setdefault(parts[0], i + 1)
    return rank


def bases(word):
    w = word.lower()
    yield w
    for suffix, repl in (
        ("ies", "y"),
        ("ing", ""),
        ("ing", "e"),
        ("ed", ""),
        ("ed", "e"),
        ("es", ""),
        ("s", ""),
        ("ly", ""),
        ("est", ""),
        ("er", ""),
        ("er", "e"),
    ):
        if w.endswith(suffix) and len(w) - len(suffix) >= 3:
            yield w[: -len(suffix)] + repl


def difficulty(word, rank):
    w = word.lower().strip()
    if " " in w or "-" in w:
        return "hard"  # phrases and compounds (carry out, custard-like)
    r = min((rank[b] for b in bases(w) if b in rank), default=None)
    if r is None:
        return "hard"
    if r <= 3000:
        return "easy"
    if r <= 5000 and len(w) <= 10:
        return "easy"
    if r <= 12000 and len(w) <= 7 and not ACADEMIC.search(w):
        return "easy"
    return "hard"


def main():
    dry = "--dry" in sys.argv
    rank = load_freq()
    text = DATA.read_text(encoding="utf-8")
    # only the lesson units; the exam bank that follows also has u1-u4 headers
    split = text.index("const examData2")
    head, tail = text[:split], text[split:]
    units = list(UNIT.finditer(head))
    if not units:
        sys.exit("no units found")

    parts, stats, last = [], {}, 0
    for idx, m in enumerate(units):
        unit = m.group(1)
        end = units[idx + 1].start() if idx + 1 < len(units) else len(head)
        block = head[m.start():end]

        def fix(e):
            en = e.group("en")
            new_pron = pron(en)
            if not new_pron:
                sys.exit(f"no pronunciation for {en!r}")
            diff = e.group("difficulty")
            if unit in ("u1", "u2", "u3", "u4"):
                diff = difficulty(en, rank)
            stats.setdefault(unit, []).append((en, new_pron, diff))
            return (
                f'{e.group("indent")}{{ en: "{en}", pron: "{new_pron}", '
                f'fa: "{e.group("fa")}", difficulty: "{diff}" }},'
            )

        parts.append(head[last:m.start()])
        parts.append(ENTRY.sub(fix, block))
        last = end
    parts.append(head[last:])
    out = "".join(parts) + tail

    for unit in sorted(stats):
        rows = stats[unit]
        hard = sum(1 for r in rows if r[2] == "hard")
        print(f"{unit}: {len(rows)} words, {hard} hard ({100 * hard / len(rows):.0f}%)")

    if dry:
        for unit in ("u1", "u2", "u3", "u4"):
            easy = [r for r in stats[unit] if r[2] == "easy"][:14]
            hard = [r for r in stats[unit] if r[2] == "hard"][:14]
            print(f"\n--- {unit} easy: " + ", ".join(r[0] for r in easy))
            print(f"--- {unit} hard: " + ", ".join(r[0] for r in hard))
        return

    DATA.write_text(out, encoding="utf-8")
    print(f"wrote {DATA}")

    # keep the Units 5-8 PSV sources in sync with the new pronunciations
    for unit in (5, 6, 7, 8):
        path = HERE / "src" / f"u{unit}.psv"
        lines = []
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line.strip() or line.lstrip().startswith("#"):
                lines.append(line)
                continue
            en, fa, _old, diff = (p.strip() for p in line.split("|"))
            lines.append(f"{en}|{fa}|{pron(en)}|{diff}")
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"updated {path.name}")


if __name__ == "__main__":
    main()
